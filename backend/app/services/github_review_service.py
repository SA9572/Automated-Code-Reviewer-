"""Pure helpers for converting AI findings into safe GitHub review comments."""

from __future__ import annotations

from pathlib import PurePosixPath
from typing import Any

from app.agents.diff_line_mapper import build_changed_line_map
from app.schemas.finding import Finding
from app.schemas.review import Review


def _safe_relative_path(path: str) -> str | None:
    if not isinstance(path, str) or not path.strip() or "\\x00" in path or "\\\\" in path:
        return None
    parsed = PurePosixPath(path)
    if parsed.is_absolute() or any(part in {"", ".", ".."} for part in parsed.parts):
        return None
    return parsed.as_posix()


def build_github_review_comments(
    findings: list[Finding],
    diff_content: str,
) -> list[dict[str, Any]]:
    """Create inline comments only for findings on added lines in the PR diff.

    GitHub's review API uses new-side line coordinates. Findings without a
    verifiable changed line remain in the review summary, never as guessed
    inline comments.
    """
    changed_lines = build_changed_line_map(diff_content)
    comments: list[dict[str, Any]] = []
    seen: set[tuple[str, int, str]] = set()

    for finding in findings:
        path = _safe_relative_path(finding.file_path)
        if path is None:
            continue
        available = changed_lines.get(path, set())
        if not available:
            continue

        start = finding.start_line
        end = finding.end_line
        if start is None and end is None:
            continue

        lower = start if start is not None else end
        upper = end if end is not None else start
        matching = sorted(line for line in available if lower <= line <= upper)
        if not matching:
            continue

        # Keep the inline anchor narrow and deterministic. The full finding
        # context remains in the comment body and overall review summary.
        line = matching[0]
        key = (path, line, finding.title)
        if key in seen:
            continue
        seen.add(key)

        body = (
            f"**{finding.severity.value} — {finding.title}**\n\n"
            f"{finding.description}\n\n"
            f"**Evidence:** {finding.evidence}\n\n"
            f"**Recommendation:** {finding.recommendation}\n\n"
            f"_Agent: {finding.agent_name} | Confidence: {finding.confidence:.0%}_"
        )
        comments.append({
            "path": path,
            "line": line,
            "side": "RIGHT",
            "body": body[:65000],
        })

    return comments


def build_github_review_body(review: Review) -> str:
    """Build the top-level review message with a compact findings summary."""
    counts = review.findings_by_severity
    lines = [
        "## Automated Code Review",
        "",
        review.summary or "The automated review has completed.",
        "",
        f"**Recommendation:** `{review.recommendation.value}`",
        f"**Total findings:** {len(review.findings)}",
        "",
        "| Severity | Count |",
        "|---|---:|",
    ]
    lines.extend(f"| {severity} | {count} |" for severity, count in counts.items())
    lines.extend(["", "### Findings"])
    for finding in review.findings[:50]:
        location = finding.file_path
        if finding.start_line is not None:
            location += f":{finding.start_line}"
            if finding.end_line is not None and finding.end_line != finding.start_line:
                location += f"-{finding.end_line}"
        lines.extend([
            "",
            f"- **{finding.severity.value}: {finding.title}** (`{location}`)",
            f"  - {finding.description[:1200]}",
            f"  - Recommendation: {finding.recommendation[:800]}",
        ])
    if len(review.findings) > 50:
        lines.extend(["", f"_And {len(review.findings) - 50} additional finding(s) stored in the review result._"])
    lines.extend([
        "",
        "Inline comments are attached only where a finding could be mapped "
        "to an added line in the reviewed pull-request diff.",
        "",
        "_Generated by Automated Code Review Board._",
    ])
    return "\n".join(lines)
